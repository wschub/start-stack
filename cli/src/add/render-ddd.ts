/** Agregado con su evento `<entidad>.created`. Sin objetos de valor: las reglas viven en `create`. */
function aggregateFile(spec: ModuleSpec, names: Names): string {
  const E = names.EntityPascal;
  const hasText = spec.fields.some((field) => field.type === "string");
  return lines([
    `import { randomUUID } from "node:crypto";`,
    `import { AggregateRoot } from "../../../../shared/domain/aggregate-root.ts";`,
    `import type { DomainEvent } from "../../../../shared/domain/domain-event.ts";`,
    `import { AppError } from "../../../../shared/errors/app-error.ts";`,
    `import type { ${E}Created } from "../events/${names.entity}-events.ts";`,
    ``,
    `/** Estado en tipos primitivos: es la forma en que se guarda y se reconstruye. */`,
    `export interface ${E}Props {`,
    `  publicId: string;`,
    ...spec.fields.map((field) => `  ${field.name}: ${TYPES[field.type].domain};`),
    `  createdAt: Date;`,
    `}`,
    ``,
    `export interface New${E}Input {`,
    ...spec.fields.map((field) => `  ${field.name}: ${TYPES[field.type].wire};`),
    `}`,
    ``,
    `export interface ${E}FactoryOptions {`,
    `  generateId?: () => string;`,
    `  now?: () => Date;`,
    `}`,
    ``,
    ...(hasText ? [`const MAX_TEXT = 200;`, ``] : []),
    `function invalid(code: string, field: string): AppError {`,
    `  return new AppError("validation", { code, details: { field } });`,
    `}`,
    ``,
    `/** Agregado ${E}: no puede existir uno inválido y al crearse anota el evento \`${names.entity}.created\`. */`,
    `export class ${E} extends AggregateRoot {`,
    `  readonly publicId: string;`,
    ...spec.fields.map((field) => `  readonly ${field.name}: ${TYPES[field.type].domain};`),
    `  readonly createdAt: Date;`,
    ``,
    `  private constructor(props: ${E}Props, events: readonly DomainEvent[] = []) {`,
    `    super(events);`,
    `    this.publicId = props.publicId;`,
    ...spec.fields.map((field) => `    this.${field.name} = props.${field.name};`),
    `    this.createdAt = props.createdAt;`,
    `    Object.freeze(this);`,
    `  }`,
    ``,
    `  /** Alta de uno nuevo. Valida y anota el evento \`${names.entity}.created\`. */`,
    `  static create(input: New${E}Input, options: ${E}FactoryOptions = {}): ${E} {`,
    `    const createdAt = (options.now ?? (() => new Date()))();`,
    `    const publicId = (options.generateId ?? randomUUID)();`,
    ...spec.fields.flatMap((field) => entityValidation(names, field)),
    `    const created: ${E}Created = {`,
    `      name: "${names.entity}.created",`,
    `      occurredAt: createdAt,`,
    `      ${names.entityCamel}Id: publicId,`,
    `    };`,
    `    return new ${E}(`,
    `      {`,
    `        publicId,`,
    ...spec.fields.map((field) => `        ${validatedValue(field)},`),
    `        createdAt,`,
    `      },`,
    `      [created],`,
    `    );`,
    `  }`,
    ``,
    `  /** Reconstruye uno ya guardado. No valida de nuevo ni anota eventos. */`,
    `  static restore(props: ${E}Props): ${E} {`,
    `    return new ${E}(props);`,
    `  }`,
    ``,
    `  toProps(): ${E}Props {`,
    `    return {`,
    `      publicId: this.publicId,`,
    ...spec.fields.map((field) => `      ${field.name}: this.${field.name},`),
    `      createdAt: this.createdAt,`,
    `    };`,
    `  }`,
    `}`,
    ``,
  ]);
}

/** Contexto nuevo en DDD: `src/contexts/<módulo>/` con su agregado, comando, consulta y evento. */
export function renderDdd(spec: ModuleSpec): Rendered {
  const names = namesOf(spec);
  const {
    module: m,
    entity,
    EntityPascal: E,
    ModulePascal: M,
    entityCamel: e,
    moduleCamel: mc,
  } = names;
  const base = `src/contexts/${m}`;
  const files = new Map<string, string>();
  const rejectable = rejectableField(spec);
  const sample = sampleObject(spec);

  files.set(
    `${base}/domain/events/${entity}-events.ts`,
    lines([
      `import type { DomainEvent } from "../../../../shared/domain/domain-event.ts";`,
      ``,
      `export interface ${E}Created extends DomainEvent {`,
      `  readonly name: "${entity}.created";`,
      `  readonly ${e}Id: string;`,
      `}`,
      ``,
    ]),
  );
  files.set(`${base}/domain/aggregates/${entity}.ts`, aggregateFile(spec, names));
  files.set(
    `${base}/domain/repositories/${entity}.repository.ts`,
    repositoryInterfaceFile(
      names,
      `../aggregates/${entity}.ts`,
      "Guarda uno nuevo y publica sus eventos de dominio.",
    ),
  );
  files.set(
    `${base}/application/dtos/${entity}-view.ts`,
    viewFile(spec, names, {
      typeName: `${E}View`,
      functionName: `to${E}View`,
      entityImport: `../../domain/aggregates/${entity}.ts`,
    }),
  );
  files.set(
    `${base}/application/commands/create-${entity}.command.ts`,
    lines([
      `import { ${E}, type New${E}Input } from "../../domain/aggregates/${entity}.ts";`,
      `import type { ${E}Repository } from "../../domain/repositories/${entity}.repository.ts";`,
      `import { type ${E}View, to${E}View } from "../dtos/${entity}-view.ts";`,
      ``,
      `export type Create${E}Input = New${E}Input;`,
      ``,
      `export class Create${E} {`,
      `  private readonly ${mc}: ${E}Repository;`,
      ``,
      `  constructor(deps: { ${mc}: ${E}Repository }) {`,
      `    this.${mc} = deps.${mc};`,
      `  }`,
      ``,
      `  /** El agregado valida y anota \`${entity}.created\`; el repositorio lo publica al guardar. */`,
      `  async execute(input: Create${E}Input): Promise<${E}View> {`,
      `    const ${e} = ${E}.create(input);`,
      `    await this.${mc}.add(${e});`,
      `    return to${E}View(${e});`,
      `  }`,
      `}`,
      ``,
    ]),
  );
  files.set(
    `${base}/application/queries/list-${m}.query.ts`,
    lines([
      `import type { ${E}Repository } from "../../domain/repositories/${entity}.repository.ts";`,
      `import { type ${E}View, to${E}View } from "../dtos/${entity}-view.ts";`,
      ``,
      `export class List${M} {`,
      `  private readonly ${mc}: ${E}Repository;`,
      ``,
      `  constructor(deps: { ${mc}: ${E}Repository }) {`,
      `    this.${mc} = deps.${mc};`,
      `  }`,
      ``,
      `  async execute(): Promise<${E}View[]> {`,
      `    return (await this.${mc}.list()).map(to${E}View);`,
      `  }`,
      `}`,
      ``,
    ]),
  );
  files.set(
    `${base}/application/permissions.ts`,
    permissionsFile(names, "../../../shared/permissions/permission.ts"),
  );
  files.set(`${base}/presentation/schemas/${entity}.schemas.ts`, schemaFile(spec, names));
  files.set(
    `${base}/presentation/controllers/${m}.controller.ts`,
    expressControllerFile(names, {
      parseBody: "../../../../shared/http/validate.ts",
      create: `../../application/commands/create-${entity}.command.ts`,
      list: `../../application/queries/list-${m}.query.ts`,
      schema: `../schemas/${entity}.schemas.ts`,
    }),
  );
  files.set(
    `${base}/presentation/routes/${m}.routes.ts`,
    routesFile(names, {
      permissions: "../../application/permissions.ts",
      controller: `../controllers/${m}.controller.ts`,
    }),
  );
  files.set(
    `${base}/infrastructure/database/prisma-${entity}.repository.ts`,
    prismaRepositoryFile(spec, names, {
      client: "../../../../generated/prisma/client.ts",
      entity: `../../domain/aggregates/${entity}.ts`,
      repository: `../../domain/repositories/${entity}.repository.ts`,
      eventBus: "../../../../shared/events/event-bus.ts",
    }),
  );

  // Pruebas
  files.set(
    `tests/integration/contexts/${m}/prisma-${entity}.repository.test.ts`,
    integrationTestFile(spec, names, {
      postgres: "../../../helpers/postgres.ts",
      entity: `../../../../src/contexts/${m}/domain/aggregates/${entity}.ts`,
      repository: `../../../../src/contexts/${m}/infrastructure/database/prisma-${entity}.repository.ts`,
      recordingBus: "../../../helpers/event-fakes.ts",
      clock: "options",
    }),
  );
  files.set(
    `tests/helpers/${m}-fakes.ts`,
    fakeRepositoryFile(names, {
      entity: `../../src/contexts/${m}/domain/aggregates/${entity}.ts`,
      repository: `../../src/contexts/${m}/domain/repositories/${entity}.repository.ts`,
      eventBus: "../../src/shared/events/event-bus.ts",
    }),
  );
  files.set(
    `tests/unit/contexts/${m}/domain/${entity}.test.ts`,
    lines([
      `import { describe, expect, it } from "vitest";`,
      `import { ${E} } from "../../../../../src/contexts/${m}/domain/aggregates/${entity}.ts";`,
      ``,
      ...domainTestBody(spec, names),
      ``,
      `  it("al crearse anota ${entity}.created, una sola vez", () => {`,
      `    const at = new Date("2026-11-15T10:00:00Z");`,
      `    const ${e} = ${E}.create(${sample}, { generateId: () => "id-1", now: () => at });`,
      ``,
      `    expect(${e}.pullEvents()).toEqual([`,
      `      { name: "${entity}.created", occurredAt: at, ${e}Id: "id-1" },`,
      `    ]);`,
      `    expect(${e}.pullEvents()).toEqual([]);`,
      `  });`,
      ``,
      `  it("al reconstruirse desde la base no anota eventos", () => {`,
      `    const stored = ${E}.create(${sample}).toProps();`,
      ``,
      `    expect(${E}.restore(stored).pullEvents()).toEqual([]);`,
      `  });`,
      `});`,
      ``,
    ]),
  );
  files.set(
    `tests/unit/contexts/${m}/application/create-${entity}.test.ts`,
    lines([
      `import { describe, expect, it } from "vitest";`,
      `import { Create${E} } from "../../../../../src/contexts/${m}/application/commands/create-${entity}.command.ts";`,
      `import { List${M} } from "../../../../../src/contexts/${m}/application/queries/list-${m}.query.ts";`,
      `import { RecordingEventBus } from "../../../../helpers/event-fakes.ts";`,
      `import { InMemory${E}Repository } from "../../../../helpers/${m}-fakes.ts";`,
      ``,
      `describe("Create${E}", () => {`,
      `  it("lo guarda, publica ${entity}.created y devuelve su vista pública", async () => {`,
      `    const bus = new RecordingEventBus();`,
      `    const ${mc} = new InMemory${E}Repository(bus);`,
      ``,
      `    const result = await new Create${E}({ ${mc} }).execute(${sample});`,
      ``,
      `    expect(result).toMatchObject(${sample});`,
      `    expect(${mc}.items).toHaveLength(1);`,
      `    expect(bus.published.map((event) => event.name)).toEqual(["${entity}.created"]);`,
      `    expect(await new List${M}({ ${mc} }).execute()).toEqual([result]);`,
      `  });`,
      ...(rejectable
        ? [
            ``,
            `  it("si el agregado rechaza los datos no se guarda ni se publica nada", async () => {`,
            `    const bus = new RecordingEventBus();`,
            `    const ${mc} = new InMemory${E}Repository(bus);`,
            ``,
            `    await expect(`,
            `      new Create${E}({ ${mc} }).execute(${sampleObject(spec, { [rejectable.name]: TYPES[rejectable.type].invalidSample ?? "" })}),`,
            `    ).rejects.toMatchObject({ code: "${errorCode(names, rejectable)}" });`,
            `    expect(${mc}.items).toEqual([]);`,
            `    expect(bus.published).toEqual([]);`,
            `  });`,
          ]
        : []),
      `});`,
      ``,
    ]),
  );
  files.set(
    `tests/acceptance/${m}.test.ts`,
    lines([
      `import request from "supertest";`,
      `import { describe, expect, it } from "vitest";`,
      `import { createApp } from "../../src/app.ts";`,
      `import { Create${E} } from "../../src/contexts/${m}/application/commands/create-${entity}.command.ts";`,
      `import { ${names.MODULE_UPPER}_PERMISSIONS } from "../../src/contexts/${m}/application/permissions.ts";`,
      `import { List${M} } from "../../src/contexts/${m}/application/queries/list-${m}.query.ts";`,
      `import { create${M}Router } from "../../src/contexts/${m}/presentation/routes/${m}.routes.ts";`,
      `import { GetUserAccess } from "../../src/contexts/identity/application/queries/get-user-access.query.ts";`,
      `import { Role } from "../../src/contexts/identity/domain/aggregates/role.ts";`,
      `import { User } from "../../src/contexts/identity/domain/aggregates/user.ts";`,
      `import { requireAuth } from "../../src/contexts/identity/presentation/middlewares/require-auth.ts";`,
      `import { createPermissionGuard } from "../../src/contexts/identity/presentation/middlewares/require-permission.ts";`,
      `import { PermissionRegistry } from "../../src/shared/permissions/permission.ts";`,
      `import { InMemoryUserRepository } from "../helpers/fakes.ts";`,
      `import { InMemory${E}Repository } from "../helpers/${m}-fakes.ts";`,
      `import { InMemoryRoleRepository, testRegistry } from "../helpers/role-fakes.ts";`,
      `import { FakeAccessTokenService } from "../helpers/session-fakes.ts";`,
      ``,
      `async function build() {`,
      `  const users = new InMemoryUserRepository();`,
      `  const roles = new InMemoryRoleRepository(users);`,
      `  const registry = new PermissionRegistry([`,
      `    ...testRegistry()`,
      `      .groups()`,
      `      .flatMap((group) => group.permissions),`,
      `    ...${names.MODULE_UPPER}_PERMISSIONS,`,
      `  ]);`,
      `  const getUserAccess = new GetUserAccess({ roles, registry });`,
      `  const ${mc} = new InMemory${E}Repository();`,
      `  const router = create${M}Router({`,
      `    authenticate: requireAuth({ accessTokens: new FakeAccessTokenService(), users }),`,
      `    authorize: createPermissionGuard({ registry, getUserAccess }),`,
      `    create${E}: new Create${E}({ ${mc} }),`,
      `    list${M}: new List${M}({ ${mc} }),`,
      `  });`,
      ``,
      `  /** Crea un usuario con un rol hecho a medida y devuelve su cabecera de autenticación. */`,
      `  const userWith = async (email: string, permissions: string[]) => {`,
      `    const user = User.create({ email, passwordHash: "x", firstName: "Ana", lastName: "Gómez" });`,
      `    await users.add(user);`,
      `    const role = Role.create({ name: \`Rol de \${email.split("@")[0]}\`, permissions });`,
      `    await roles.add(role);`,
      `    await roles.setUserRoles(user.publicId, [role.publicId]);`,
      `    return \`Bearer access:\${user.publicId}\`;`,
      `  };`,
      ``,
      `  return { app: createApp({ routers: [router] }), userWith };`,
      `}`,
      ``,
      ...acceptanceTestBody(spec, names),
    ]),
  );

  return {
    files,
    edits: [
      {
        path: "src/composition.ts",
        marker: "imports",
        lines: [
          `import { Create${E} } from "./contexts/${m}/application/commands/create-${entity}.command.ts";`,
          `import { ${names.MODULE_UPPER}_PERMISSIONS } from "./contexts/${m}/application/permissions.ts";`,
          `import { List${M} } from "./contexts/${m}/application/queries/list-${m}.query.ts";`,
          `import { Prisma${E}Repository } from "./contexts/${m}/infrastructure/database/prisma-${entity}.repository.ts";`,
          `import { create${M}Router } from "./contexts/${m}/presentation/routes/${m}.routes.ts";`,
        ],
      },
      {
        path: "src/composition.ts",
        marker: "permissions",
        lines: [`    ...${names.MODULE_UPPER}_PERMISSIONS,`],
      },
      {
        path: "src/composition.ts",
        marker: "wiring",
        lines: [
          `  const ${mc}Repository = new Prisma${E}Repository(prisma, events);`,
          `  const ${mc}Router = create${M}Router({`,
          `    authenticate,`,
          `    authorize,`,
          `    create${E}: new Create${E}({ ${mc}: ${mc}Repository }),`,
          `    list${M}: new List${M}({ ${mc}: ${mc}Repository }),`,
          `  });`,
          ``,
        ],
      },
      { path: "src/composition.ts", marker: "routers", lines: [`      ${mc}Router,`] },
      { path: "prisma/schema.prisma", marker: "models", lines: prismaModel(spec, names) },
      {
        path: "src/shared/i18n/messages.ts",
        marker: "messages-en",
        lines: messageLines(spec, names, "en"),
      },
      {
        path: "src/shared/i18n/messages.ts",
        marker: "messages-es",
        lines: messageLines(spec, names, "es"),
      },
    ],
  };
}
